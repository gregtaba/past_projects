from docx import Document

# === Εισαγωγή Δεδομένων ===
employee_name = input("Εισάγετε το πλήρες όνομα του υπαλλήλου: ")
employer_name = input("Εισάγετε το όνομα της εταιρείας ή του εργοδότη: ")
effective_date = input("Εισάγετε την ημερομηνία έναρξης ισχύος (π.χ. 7 Μαΐου 2025): ")
duration = input("Εισάγετε τη διάρκεια της ρήτρας μη ανταγωνισμού (π.χ. 12 μήνες): ")
restricted_area = input("Εισάγετε την γεωγραφική περιοχή ή το πεδίο εφαρμογής (π.χ. Περιοχή Αττικής): ")
compensation = input("Εισάγετε την αποζημίωση κατά τη διάρκεια της ρήτρας μη ανταγωνισμού: ")
penalty_amount = input("Εισάγετε το ποσό της ποινής σε περίπτωση παραβίασης της ρήτρας μη ανταγωνισμού: ")

# === Δημιουργία Εγγράφου Word ===
doc = Document()
doc.add_heading("Ρήτρα Μη Ανταγωνισμού", level=1)

doc.add_paragraph()

doc.add_paragraph(f"Η παρούσα Ρήτρα Μη Ανταγωνισμού (\"Σύμβαση\") τίθεται σε ισχύ από {effective_date}, "
                  f"μεταξύ της εταιρείας {employer_name} (\"Εταιρεία\") και του υπαλλήλου/συνεργάτη {employee_name} (\"Υπάλληλος\").")

doc.add_paragraph("ΕΝΩ, η Εταιρεία επιθυμεί να προστατεύσει τα νόμιμα επιχειρηματικά της συμφέροντα, "
                  "και ο Υπάλληλος έχει συμφωνήσει σε ορισμένους περιορισμούς ως αντάλλαγμα για τη συνέχιση της συνεργασίας του με την Εταιρεία.")

doc.add_paragraph("ΕΠΟΜΕΝΩΣ, με αντάλλαγμα τις αμοιβαίες υποσχέσεις και συμφωνίες που περιλαμβάνονται στην παρούσα, "
                  "οι συμβαλλόμενοι συμφωνούν ως εξής:")

paragraph = doc.add_paragraph()

run_title = paragraph.add_run("**1. Υποχρέωση Μη Ανταγωνισμού**\n")
run_title.bold = True

# Κανονικό κείμενο
paragraph.add_run(
    f"Ο Υπάλληλος συμφωνεί ότι για διάστημα {duration} μετά τη λήξη της συνεργασίας του με την Εταιρεία, "
    f"δεν θα συμμετάσχει άμεσα ή έμμεσα σε οποιαδήποτε επιχειρηματική δραστηριότητα που ανταγωνίζεται "
    f"τις δραστηριότητες της Εταιρείας εντός της περιοχής {restricted_area}."
)

# Παράγραφος 2 - Αποζημίωση
paragraph = doc.add_paragraph()
run_title = paragraph.add_run("**2. Αποζημίωση\n")
run_title.bold = True
paragraph.add_run(
    f"Ο Υπάλληλος αναγνωρίζει ότι κατά τη διάρκεια της περιόδου της ρήτρας μη ανταγωνισμού, "
    f"η Εταιρεία θα παρέχει αποζημίωση ύψους {compensation}."
)

# Παράγραφος 3 - Ποινή για Παράβαση
paragraph = doc.add_paragraph()
run_title = paragraph.add_run("**3. Ποινή για Παράβαση**\n")
run_title.bold = True
paragraph.add_run(
    f"Σε περίπτωση παράβασης της ρήτρας μη ανταγωνισμού, "
    f"ο Υπάλληλος θα είναι υπόχρεος να καταβάλει στην Εταιρεία ποσό {penalty_amount} ως ποινή."
)

# Παράγραφος 4 - Αναγνώριση
paragraph = doc.add_paragraph()
run_title = paragraph.add_run("**4. Αναγνώριση**\n")
run_title.bold = True
paragraph.add_run(
    "Ο Υπάλληλος αναγνωρίζει ότι η παρούσα συμφωνία είναι εύλογη ως προς το πεδίο και τη διάρκεια "
    "και είναι αναγκαία για την προστασία των νόμιμων επιχειρηματικών συμφερόντων της Εταιρείας."
)

# Παράγραφος 5 - Εφαρμοστέο Δίκαιο
paragraph = doc.add_paragraph()
run_title = paragraph.add_run("**5. Εφαρμοστέο Δίκαιο**\n")
run_title.bold = True
paragraph.add_run(
    "Η παρούσα Σύμβαση θα διέπεται από και θα ερμηνεύεται σύμφωνα με το δίκαιο της εφαρμοστέας δικαιοδοσίας."
)


doc.add_paragraph("ΕΝ ΥΠΟΓΡΑΦΩ, οι συμβαλλόμενοι υπέγραψαν την παρούσα Σύμβαση την πρώτη ημερομηνία αναγραφής της.")

# === Υπογραφή ===
doc.add_paragraph("\n\n______________________________")
doc.add_paragraph(f"{employee_name} (Υπάλληλος)")

doc.add_paragraph("\n\n______________________________")
doc.add_paragraph(f"{employer_name} (Εταιρεία)")

# === Αποθήκευση Εγγράφου ===
filename = f"Non_Compete_{employee_name.replace(' ', '_')}.docx"
doc.save(filename)

print(f"\nΗ συμφωνία μη ανταγωνισμού αποθηκεύτηκε ως: {filename}")
